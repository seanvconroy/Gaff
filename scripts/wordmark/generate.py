"""
Draws the Gaff wordmark as outlines (UX-DS-22, Q29) and writes src/ui/wordmarkPaths.ts.

The wordmark is "gaff." exactly as the product set it in live text until November 2026:
Fraunces, weight 600, optical size 144, letter-spacing -0.01em. With that letter-spacing a
browser sets two separate "f"s (no ligature), and their crossbars meet: that is the key.
This script takes the same outlines from the same font file, so nothing is redrawn.

It is run by hand, once, and again only if the lettering is ever changed on purpose:

    pip install fonttools brotli uharfbuzz
    python3 scripts/wordmark/generate.py
    pnpm exec prettier --write src/ui/wordmarkPaths.ts

Fraunces is under the SIL Open Font License (public/fonts/LICENSE-Fraunces.txt).
"""

from __future__ import annotations

import io
import sys
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "node_modules/@fontsource-variable/fraunces/files/fraunces-latin-opsz-normal.woff2"
OUTPUT = ROOT / "src/ui/wordmarkPaths.ts"

TEXT = "gaff."
WEIGHT = 600
OPTICAL_SIZE = 144
LETTER_SPACING_EM = -0.01
# Browsers switch optional ligatures off when letter-spacing isn't zero (CSS Text 3, section 8.2),
# which is why the wordmark has always had two "f"s whose crossbars meet, not the "ff" ligature.
FEATURES = {"liga": False, "clig": False, "kern": True}


def main() -> None:
    font_file = Path(sys.argv[1]) if len(sys.argv) > 1 else FONT
    tt = TTFont(font_file)
    units_per_em = tt["head"].unitsPerEm
    tt.flavor = None  # HarfBuzz reads the uncompressed font
    raw = io.BytesIO()
    tt.save(raw)

    font = hb.Font(hb.Face(raw.getvalue()))
    font.set_variations({"wght": WEIGHT, "opsz": OPTICAL_SIZE})

    buffer = hb.Buffer()
    buffer.add_str(TEXT)
    buffer.guess_segment_properties()
    hb.shape(font, buffer, FEATURES)

    spacing = LETTER_SPACING_EM * units_per_em
    letters = RecordingPen()
    full_stop = RecordingPen()
    x = 0.0
    names = []
    for info, position in zip(buffer.glyph_infos, buffer.glyph_positions):
        name = font.glyph_to_string(info.codepoint)
        names.append(name)
        target = full_stop if name == "period" else letters
        # Font outlines have y pointing up; SVG has it pointing down.
        pen = TransformPen(target, (1, 0, 0, -1, x + position.x_offset, -position.y_offset))
        font.draw_glyph_with_pen(info.codepoint, pen)
        x += position.x_advance + spacing

    bounds = BoundsPen(None)
    letters.replay(bounds)
    full_stop.replay(bounds)
    x_min, y_min, x_max, y_max = bounds.bounds
    # The drawing is cropped to its ink, on whole font units.
    left, top = int(x_min // 1), int(y_min // 1)
    width, height = int(-(-x_max // 1)) - left, int(-(-y_max // 1)) - top

    def path(recording: RecordingPen) -> str:
        svg = SVGPathPen(None, ntos=lambda value: str(int(round(value))))
        recording.replay(TransformPen(svg, (1, 0, 0, 1, -left, -top)))
        return svg.getCommands()

    ink_em = height / units_per_em
    OUTPUT.write_text(
        "\n".join(
            [
                "// Generated by scripts/wordmark/generate.py from Fraunces"
                f" (weight {WEIGHT}, optical size {OPTICAL_SIZE},",
                f"// letter-spacing {LETTER_SPACING_EM}em; glyphs: {' '.join(names)}). Do not edit.",
                "",
                f"/** The drawing, cropped to its ink, in font units ({units_per_em} to the em). */",
                f"export const wordmarkSize = {{ width: {width}, height: {height} }} as const;",
                "",
                "/**",
                " * The drawing's height as a share of the type size it was set at: the old 28px text",
                f" * wordmark is {ink_em * 28:.2f}px of ink.",
                " */",
                f"export const wordmarkInkPerEm = {ink_em};",
                "",
                '/** "gaff": the two "f"s meet at their crossbars and read as a key. */',
                f"export const wordmarkLetters = '{path(letters)}';",
                "",
                "/** The full stop, drawn apart so it can take the brand colour. */",
                f"export const wordmarkFullStop = '{path(full_stop)}';",
                "",
            ]
        )
    )
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {width} x {height} units, glyphs {' '.join(names)}")
    print(f"ink origin in text space: left {left}, top {top} (baseline at y = 0)")


if __name__ == "__main__":
    main()
